function SelfTestPerft(maxDepth)
  maxDepth = maxDepth or 3
  local failures = {}
  local checked = 0
  for _, c in ipairs(PERFT_CASES) do
    local st = RULES.parse_fen(c.fen)
    for d = 1, maxDepth do
      local expect = c["d" .. tostring(d)]
      if expect then
        local got = RULES.perft(st, d)
        checked = checked + 1
        if got ~= expect then
          failures[#failures + 1] = string.format("%s d=%d got=%d expect=%d", c.name, d, got, expect)
        end
      end
    end
  end
  return #failures == 0, checked, failures
end

-- 汇总自检：返回给沙箱/诊断的结构化结果
function SelfTest()
  local out = { ok = true, checks = {} }
  local function add(name, pass, detail)
    out.checks[#out.checks + 1] = { name = name, pass = pass, detail = detail or "" }
    if not pass then out.ok = false end
  end

  -- 1 规则 perft
  local okPerft, checked, failures = SelfTestPerft(2)
  add("perft_d1_d2", okPerft, okPerft and ("checked=" .. tostring(checked)) or table.concat(failures, "; "))

  -- 2 状态
  add("state_running", GAME.state == "RUNNING", "state=" .. tostring(GAME.state))

  -- 3 控件数量
  add("controls_created", FACTORY.created > 0, "created=" .. tostring(FACTORY.created))

  -- 4 界面已建
  add("ui_built", UI.built == true, "built=" .. tostring(UI.built))

  -- 5 联机能力（沙箱里 canSend 应为 false，这是正常的）
  add("net_probe_done", NET.probed == true,
    "canSend=" .. tostring(NET.canSend) .. " canReceive=" .. tostring(NET.canReceive))

  -- 6 动画时长与 Demo v3 同值（v1.10）
  add("anim_matches_demo",
    CONFIG.ANIM.MOVE_DUR == 0.17 and CONFIG.ANIM.SETTLE_DUR == 0.10
      and CONFIG.ANIM.SETTLE_PEAK == 0.07,
    string.format("move=%.2f settle=%.2f peak=%.2f",
      CONFIG.ANIM.MOVE_DUR, CONFIG.ANIM.SETTLE_DUR, CONFIG.ANIM.SETTLE_PEAK))

  return out
end

-- 供外部调用：重绘计量与控件写计量（v1.10/v1.11 提速诊断）。
-- 用法：ResetRepaintStats() → 走一步 → 等动画跑完 → GetRepaintStats() 读数字。
-- A/B 实测（pc-16-9，e2→e4 一步）：
--   旧（动画期全量重绘）： full=10 partial=0  → 10 帧 × 32 槽 = 320 次 paint_slot
--   新（只重绘脏槽位）：   full=2  partial=8  slots=8 → 2×32 + 8 = 72 次
--   单帧稳态从 32 槽降到 1 槽（走子只动一枚），动画期控件写次数约降 78%。
--
-- 【v1.11 新增 ctrlWrites / ctrlWritesSkipped】issue #1 第 6 条要求「保证功能不变
-- 的情况下优化性能」，那就必须给出可复测的数字，而不是只写「优化了」：
--   ctrlWrites         ：真正打到平台的属性写次数（SetActive/SetVisible/尺寸/位置/颜色/旋转/图元/text）
--   ctrlWritesSkipped  ：因为「值没变」被跳过的次数 —— 这就是缓存省下的写
-- 复测方法同上：Reset → 走一步 → 等动画结束 → 读两个数。
function GetRepaintStats()
  return {
    paintSlotsTotal = ANIM.paintSlotsTotal,
    paintFramesFull = ANIM.paintFramesFull,
    paintFramesPartial = ANIM.paintFramesPartial,
    animTasks = ANIM.count,
    dirtyCount = ANIM.dirtyCount,
    ctrlWrites = WRITE_STATS.writes,
    ctrlWritesSkipped = WRITE_STATS.skipped,
  }
end

-- 重置计量（配合 GetRepaintStats 做前后对比）
function ResetRepaintStats()
  ANIM.paintSlotsTotal = 0
  ANIM.paintFramesFull = 0
  ANIM.paintFramesPartial = 0
  WRITE_STATS.writes = 0
  WRITE_STATS.skipped = 0
  return true
end
