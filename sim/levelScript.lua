  if GAME.review.idx == 0 then return CONFIG.TEXT.REVIEW_AT_START end
  local total = #GAME.history - 1
  local s = string.gsub(CONFIG.TEXT.REVIEW_STEP, "{n}", tostring(GAME.review.idx))
