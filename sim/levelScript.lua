-- 校验配置：三项模板索引必须非 0
local function validate_config()
  local missing = {}
  if CONFIG.CONTAINER_NODE_INDEX == 0 then missing[#missing + 1] = "CONTAINER_NODE_INDEX" end
  if CONFIG.PREFAB_TEXT_BOX == 0 then missing[#missing + 1] = "PREFAB_TEXT_BOX" end
  if CONFIG.PREFAB_CURSOR_AREA == 0 then missing[#missing + 1] = "PREFAB_CURSOR_AREA" end
  -- PREFAB_IMAGE 是必填：棋子只有「图元拼」这一档，全靠图片控件实现。
  -- 缺它棋盘上不会出现任何棋子，属于致命配置错误，必须在启动时就拒绝并报清楚。
  if CONFIG.PREFAB_IMAGE == 0 then
    missing[#missing + 1] = "PREFAB_IMAGE（棋子用图元绘制，必须建「图片」控件模板）"
  end
  if #missing > 0 then
    return false, table.concat(missing, ", ")
  end
  return true, nil
end

-- 检查画布尺寸是否有效（有限正数）
local function read_canvas()
  local ok, w, h = pcall(function() return game.GetUICanvasSize() end)
  if not ok then return nil, nil, "GetUICanvasSize 调用失败" end
  if type(w) ~= "number" or type(h) ~= "number" then return nil, nil, "返回值不是数字" end
  if w ~= w or h ~= h then return nil, nil, "返回 NaN" end
  if w <= 0 or h <= 0 then return nil, nil, "返回非正数" end
  if math.isinf(w) or math.isinf(h) then return nil, nil, "返回无穷" end
  return w, h, nil
end

-- 获取挂载容器
local function read_container()
  -- 【为什么用 script.object】
  -- 官方编辑器指南与 API 文档示例都用 script.object 作为挂载容器：
  -- 脚本挂在「容器节点」上，script.object 就是那个容器节点。
  -- game.GetClientUIControl(controlId) 的参数是**运行时 ID**（文档 L176），
  -- 不是用户填的**模板索引**，两者不是一回事，不能拿来取容器。
  -- 因此：优先 script.object；它为 nil 时再用 GetClientUIControl 兜底（兼容旧写法）。
  local ok, host = pcall(function() return script.object end)
  if ok and host ~= nil then
    return host
  end
  local ok2, ctrl = pcall(function()
    return game.GetClientUIControl(CONFIG.CONTAINER_NODE_INDEX)
  end)
  if ok2 and ctrl ~= nil then
    return ctrl
  end
  return nil, "取不到挂载容器（script.object 与 GetClientUIControl 都返回空）"
end

local function build_all_ui()
  if UI.built then return true end
  local w, h, err = read_canvas()
  if not w then
    log_info("画布尚未就绪：%s", tostring(err))
    return false
  end
  -- 先取挂载容器：所有自建控件都挂在它下面
  -- 取不到时不阻断启动，改用 nil 父级（挂到默认容器根），只记一条日志。
  -- 理由：真机上 script.object 一般可用；异常环境下退化为默认根，
  --       仍能创建控件并显示，比直接放弃启动好得多。
  local host, hostErr = read_container()
  if host == nil then
    log_once("no_host", "挂载容器未取到（%s），控件将挂到默认根", tostring(hostErr))
  end
  UI.host = host   -- 可能为 nil，create_* 会原样传给 InstantiateClientUIControl

  UI.L = LAYOUT.compute(w, h)
  GAME.lastCanvasW, GAME.lastCanvasH = w, h

  -- 【棋盘图元数】由 PIECE_ART 自动算出，不需要加载外部数据文件
  PRIM_MAX = piece_prim_max()
  if PRIM_MAX < 1 then PRIM_MAX = 1 end

  -- ===== 背景层（必须先建，同级先出现的在下）=====
  -- 平台图元不支持真渐变，只能用「多条横向色带」逼近竖向渐变。
  -- 【浅色主题必须加密色带】v1.7 用的是 3 条（各 300px）：
  --   深靛蓝外壳下 234/242/248 这种相邻只差 ~8 点亮度、画布本身又暗，分界根本看不出来；
  --   换成浅米外壳后，同样的三档在浅底上会显出**两条硬横线**（模拟器截图实测）。
  -- Demo 用的是真 linear-gradient（0% / 46% / 100% 三个停靠点），
  -- 这里按同样的停靠点做线性插值 + 24 条色带，肉眼即连续渐变。
  local BG_STOPS = {
    { 0.00, CONFIG.COLOR.BG_BOTTOM },   -- 画布最下
    { 0.46, CONFIG.COLOR.BG },          -- 与 Demo 的 46% 停靠点一致
    { 1.00, CONFIG.COLOR.BG_TOP },      -- 最上
  }
  -- 在 t（0=画布底, 1=画布顶）处对三段停靠点做线性插值
  local function bg_color_at(t)
    local last = BG_STOPS[#BG_STOPS]
    if t <= BG_STOPS[1][1] then
      local c = BG_STOPS[1][2]
      return { c[1], c[2], c[3], 255 }
    end
    if t >= last[1] then
      return { last[2][1], last[2][2], last[2][3], 255 }
    end
    for i = 2, #BG_STOPS do
      local a, b = BG_STOPS[i - 1], BG_STOPS[i]
      if t <= b[1] then
        local span = b[1] - a[1]
        local k = (span > 0) and ((t - a[1]) / span) or 0
        local ca, cb = a[2], b[2]
        -- +0.5 再取整 = 四舍五入，避免连续渐变出现人为的整体偏暗
        return {
          math.floor(ca[1] + (cb[1] - ca[1]) * k + 0.5),
          math.floor(ca[2] + (cb[2] - ca[2]) * k + 0.5),
          math.floor(ca[3] + (cb[3] - ca[3]) * k + 0.5),
          255,
        }
      end
    end
    return { last[2][1], last[2][2], last[2][3], 255 }
  end
  UI.bg = {}
  local BG_BANDS = 24
  local bandH = h / BG_BANDS
  for i = 1, BG_BANDS do
    -- 每条带取**中心**位置的颜色采样，误差被摊到半条带，比取边界更平滑
    local t = (i - 0.5) / BG_BANDS
    UI.bg[i] = create_text({
      name = "bgband" .. tostring(i), parent = UI.host,
      -- 高度 +1：相邻带重叠 1px，把取整留下的细缝盖掉
      x = 0, y = (i - 1) * bandH, w = w, h = bandH + 1,
      bg = bg_color_at(t), text = "",
    })
  end

  build_board()
  build_panel()
  build_result_panel()
  build_promo_dialog()
  build_confirm_dialog()
  UI.built = true
  GAME.uiReady = true

  log_info("棋子图元：6 种 × 2 方，单枚最多 %d 个控件", PRIM_MAX)

  -- 统一启用所有已创建控件（创建时全部 SetActive(false)）
  for i = 1, #FACTORY.cleanup do
    local ctrl = FACTORY.cleanup[i]
    if ctrl ~= nil then
      ctrl:SetActive(true)
      ctrl:SetVisible(true)
    end
  end
  -- 【层级】全部建完后，把命中区统一提到最顶层。
  -- 原因：面板/弹窗都是在 build_board、build_panel 之后创建的，
  -- 同级后出现的节点在上，会把先建的棋盘命中区与面板按钮命中区盖住 → 点击全部失效
  -- （模拟器实测：不走这一步则棋盘和按钮都点不动）。
  -- 棋盘命中区与面板按钮命中区都要提；弹窗自己的命中区由 show_*/hide_* 单独管理。
  local function raise_hit(c)
    if c ~= nil then pcall(function() c:SetAsLastSibling() end) end
  end
  for sq = 0, 63 do raise_hit(UI.hitAreas[sq]) end
  raise_hit(UI.panel.hitNew)
  raise_hit(UI.panel.hitResign)
  raise_hit(UI.panel.hitDraw)
  raise_hit(UI.panel.hitLocal)
  -- 复盘命中区同样要提（它们在 build_panel 里建，之后建的结算/确认弹窗会盖住）
  raise_hit(UI.review.hitToggle)
  raise_hit(UI.review.hitStart)
  raise_hit(UI.review.hitPrev)
  raise_hit(UI.review.hitNext)
  raise_hit(UI.review.hitEnd)
  -- 音效开关命中区（v1.10）：它在面板下方，同样会被之后建的弹窗盖住
  raise_hit(UI.panel.hitSfx)
  -- 音效按钮文案按当前开关状态同步（`音效：开` / `音效：关`）
  sync_sfx_button()
  -- 结算/升变/求和弹窗初始隐藏
  hide_result()
  hide_promo()
  hide_confirm()
  -- 复盘相关控件初始隐藏；第三行常驻键显示为「看历史」
  show_review_buttons(false)
  ui_set_active(UI.review.btnToggle, true)
  ui_set_active(UI.review.hitToggle, true)
  UI.review.btnToggle.text = CONFIG.TEXT.BTN_REVIEW_HISTORY

  log_info("界面构建完成：控件 %d 个，画布 %dx%d，格宽 %.1f",
    FACTORY.created, w, h, UI.L.cell)
  return true
end

local function cleanup_all()
  -- 反向释放：注销监听 → 销毁控件
  for i = #INPUT.registered, 1, -1 do
    local ctrl = INPUT.registered[i]
    if ctrl ~= nil then
      pcall(function()
        if CLICK_EVENT ~= nil then ctrl:RemoveCursorEventListeners(CLICK_EVENT) end
      end)
    end
  end
  INPUT.registered = {}

  for i = #FACTORY.cleanup, 1, -1 do
    local ctrl = FACTORY.cleanup[i]
    if ctrl ~= nil then
      pcall(function() game.DestroyClientUIControl(ctrl) end)
    end
  end
  FACTORY.cleanup = {}
  UI.built = false
  GAME.uiReady = false
end

-- ===== 生命周期回调 =====
function OnInit()
  GAME.state = "NEW"
  log_info("脚本初始化")
end

function OnStart()
  GAME.state = "STARTING"
  GAME.startupRetry = 0

  -- ① 先验证配置（配置错误立即报错，不重试）
  local cfgOk, missing = validate_config()
  if not cfgOk then
    log_err(CONFIG.TEXT.ERR_CONFIG)
    emit_fault("CFG_MISSING", "STARTING", "配置缺失: " .. tostring(missing), nil, "CONFIG 第 1 区")
    GAME.state = "FAILED"
    return
  end

  -- ② 探测联机能力（无论成功与否都不阻断启动）
  net_probe()

  -- ③ 尝试构建界面（画布未就绪时由 OnUpdate 有限重试）
  if not build_all_ui() then
    log_info("界面尚未就绪，将在逐帧里有限重试（预算 %d 帧）", CONFIG.STARTUP_RETRY_BUDGET)
    script:EnableUpdate(true)
    return
  end

  -- ④ 解析点击事件枚举
  CLICK_EVENT = resolve_click_event()
  if CLICK_EVENT == nil then
    log_err("取不到光标点击事件枚举，界面不可交互")
    emit_fault("EVENT_ENUM_MISSING", "STARTING", "Enum.CursorEventType 无可用值", nil, "API 文档 L424-435")
    GAME.state = "FAILED"
    return
  end

  -- ⑤ 注册输入
  register_all_input()

  -- ⑥ 注册联机接收
  net_register_receive()

  -- ⑦ 开局
  new_game()
  GAME.state = "RUNNING"
  script:EnableUpdate(true)

  log_info("启动完成：状态=%s 控件=%d 联机发送=%s 接收=%s 同屏=%s",
    GAME.state, FACTORY.created, tostring(NET.canSend), tostring(NET.canReceive), tostring(GAME.localMode))

  -- 启动汇总（一次）
  log_info("容器索引=%d 脚本短名=%s 画布=%dx%d",
    CONFIG.CONTAINER_NODE_INDEX, CONFIG.SCRIPT_SHORT_NAME,
    GAME.lastCanvasW or -1, GAME.lastCanvasH or -1)
end

function OnEnable()
  log_info("脚本启用")
end

function OnUpdate(dt)
  -- ① STARTING 阶段：只推进就绪重试，不推进玩法
  if GAME.state == "STARTING" then
    GAME.startupRetry = GAME.startupRetry + 1
    if GAME.startupRetry > CONFIG.STARTUP_RETRY_BUDGET then
      emit_fault("STARTUP_TIMEOUT", "STARTING",
        "画布或容器在 " .. tostring(CONFIG.STARTUP_RETRY_BUDGET) .. " 帧内仍未就绪",
        nil, "OnUpdate 重试计数")
      GAME.state = "FAILED"
      return
    end
    if build_all_ui() then
      CLICK_EVENT = resolve_click_event()
      if CLICK_EVENT == nil then
        emit_fault("EVENT_ENUM_MISSING", "STARTING", "Enum.CursorEventType 无可用值", nil, "API 文档 L424-435")
        GAME.state = "FAILED"
        return
      end
      register_all_input()
      net_register_receive()
      new_game()
      GAME.state = "RUNNING"
    end
    return
  end

  if GAME.state ~= "RUNNING" then return end

  -- ② 时间增量校验（异常值跳过本帧）
  if type(dt) ~= "number" or dt ~= dt or dt <= 0 or math.isinf(dt) then return end

  -- ②.5 复盘中冻结棋局：不累计用时、不扣棋钟、不触发超时判负。
  -- 复盘是「回看」，对局时间不能因为看历史而流逝（对局中看历史尤其重要）。
  -- 【注意】复盘只冻结棋局，动画照样要推进，否则棋子会卡在半路。
  local reviewing = (GAME.review ~= nil)

  -- ②.6 动画统一推进（放最前：即便终局/复盘，动画也要走完）
  --
  -- 【必须在这里补一次棋子重绘】动画只改 slot.x/y/scale/lift 这些**数据**，
  -- 真正把数据写到控件上的是 paint_slot，而 paint_slot 只在 render_pieces 里被调用。
  -- 早先只推进 ANIM 不重绘，结果是：棋子一步走完位置数据早就是终点了，
  -- 但画面上还停在起点（模拟器实测：e2→e4 之后兵仍在 e2，目标格只多了个高亮）。
  --
  -- 【v1.10 提速：动画期间只重绘脏槽位】
  --   旧写法是动画期间每帧 render_pieces() 全量重绘：重建 bySq（64 格 + 32 槽）
  --   → 遍历 32 槽 → 每槽 paint_slot 做 6 遍形状遍历、每个图元 3~4 次控件写。
  --   32 枚 × 数十图元 ≈ 每帧数千次控件写 —— 这就是「不跟手」的根因。
  --   现在 anim_update 会登记本帧真正动过的槽位（ANIM.dirty），只重绘那几个。
  --
  --   为什么不会漏绘：
  --   · 槽位**归属**（slot.sq / slot.key）只在全量 render_pieces、apply_move、
  --     reset_piece_slots 里改，这三处之后都会走全量渲染；
  --   · 动画任务只改 x/y/scale/lift/fading，不改归属 → 归属在动画期间是稳定的；
  --   · 动画全部跑完的那一帧还需要「收尾全量」：ANIM.count 变 0 时按 needsRepaint
  --     再走一次全量 render_pieces，把可能的半格/旧位置彻底刷干净（见下）。
  if GAME.animated then
    anim_update(dt)
    if GAME.uiReady then
      local dirty, dirtyCount = anim_take_dirty()
      if ANIM.count > 0 then
        -- 动画进行中：只重绘本帧动过的槽位（通常 1~2 个，开局弹入时最多 32 个）
        if dirty ~= nil then render_pieces(dirty, dirtyCount) end
        GAME.needsRepaint = true      -- 记下「收尾还要全量刷一次」
      elseif GAME.needsRepaint then
        -- 动画刚跑完这一帧：补一次全量重绘收尾，然后清标记
        GAME.needsRepaint = false
        render_pieces()
      end
    end
  end
  if GAME.uiReady then anim_update_hilites(dt) end

  if reviewing then return end

  -- ③ 本局用时累加（结算说明行「本局用时 MM:SS」用）
  if not GAME.over then
    GAME.elapsedSec = (GAME.elapsedSec or 0) + dt
  end

  -- ④ 棋钟：只有轮到的一方在扣时；终局后不扣
  if not GAME.over then
    if GAME.st.turn == WHITE then
      GAME.clockWhite = GAME.clockWhite - dt
      -- 音效：首次跌破 SFX_LOW_TIME_SEC 时提示一次（每方各一次，靠 lowTimeFired 防重复）
      -- 必须在扣时之后、判负之前判：判负那一刻也顺手会播 GAME_END，不再补提示音。
      if not SFX.lowTimeFired[1] and GAME.clockWhite > 0
         and GAME.clockWhite <= CONFIG.SFX_LOW_TIME_SEC then
        SFX.lowTimeFired[1] = true
        sfx_play("low_time")
      end
      if GAME.clockWhite <= 0 then
        GAME.clockWhite = 0
        GAME.over = true
        GAME.resultText = CONFIG.TEXT.RESULT_TIMEOUT_WHITE
        GAME.resultSub = CONFIG.TEXT.SUB_TIMEOUT_WHITE
        show_result()
      end
    else
      GAME.clockBlack = GAME.clockBlack - dt
      if not SFX.lowTimeFired[2] and GAME.clockBlack > 0
         and GAME.clockBlack <= CONFIG.SFX_LOW_TIME_SEC then
        SFX.lowTimeFired[2] = true
        sfx_play("low_time")
      end
      if GAME.clockBlack <= 0 then
        GAME.clockBlack = 0
        GAME.over = true
        GAME.resultText = CONFIG.TEXT.RESULT_TIMEOUT_BLACK
        GAME.resultSub = CONFIG.TEXT.SUB_TIMEOUT_BLACK
        show_result()
      end
    end
  end

  -- ④ 求和冷却倒计时
  for i = 1, 2 do
    if GAME.drawCooldown[i] > 0 then
      GAME.drawCooldown[i] = math.max(0, GAME.drawCooldown[i] - dt)
    end
  end

  -- ⑤ 棋钟文本按 CLOCK_REFRESH_SEC 刷新（不逐帧写文本）
  GAME.clockTextTimer = GAME.clockTextTimer + dt
  if GAME.clockTextTimer >= CONFIG.CLOCK_REFRESH_SEC then
    GAME.clockTextTimer = 0
    update_clock_text()
  end
end

