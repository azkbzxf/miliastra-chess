-- 第 5.6 区：SFX（音效播放与开关，v1.10）
-- -----------------------------------------------------------------------------
-- 【为什么单独一个区】音效是横切关注点：棋盘、面板按钮、终局、棋钟都要用。
--   放在 ANIM 之后、UI 之前，是因为 UI 构建时要建「音效开关按钮」，需要 sfx_enabled。
--
-- 【平台 API】(见 get_client_document「客户端控件API文档」第 6 节 (4))
--   game.PlayAudio2D(audioId: integer) -> integer   播放 2D 音效，返回实例 ID
--   game.StopAudio(audioInstanceId: integer)
--   game.IsAudioAlive(audioInstanceId: integer)
--
-- 【为什么必须 pcall 包住】模拟器默认静音；某些环境可能根本没实现这几个函数。
--   不加保护的话第一声就把整个 OnUpdate/点击回调打断，等于游戏卡死。
--   失败只 printerr **一次**（用 log_once 思路），避免每帧刷屏把真日志淹掉。
-- =============================================================================
local SFX = {
  enabled = true,          -- 音效总开关（面板按钮控制）
  ids = {},                -- 环形缓冲：最近播过的实例 ID
  count = 0,
  head = 0,
  -- 能力探测结果：nil = 还没试过；true = 可用；false = 不可用（不再重试）
  available = nil,
  failLogged = false,      -- 失败日志是否已打过（只打一次）
  badKeyLogged = {},       -- 已报过「键名不存在」的音效名（每个键名只报一次，防刷屏）
  lowTimeFired = { [1] = false, [2] = false },   -- 双方是否已播过「剩时不足」提示
  overFired = false,       -- 终局音是否已播（防重复）
}

-- 记录一个音效实例 ID（环形缓冲，满了覆盖最旧的）
local function sfx_remember(instId)
  if instId == nil then return end
  local cap = CONFIG.SFX_HISTORY
  if cap <= 0 then return end
  SFX.head = (SFX.head % cap) + 1
  SFX.ids[SFX.head] = instId
  if SFX.count < cap then SFX.count = SFX.count + 1 end
end

-- 停掉缓冲区里所有还活着的实例（新开一局/销毁时调用，防止上一局的尾音串过来）
local function sfx_stop_all()
  for i = 1, CONFIG.SFX_HISTORY do
    local id = SFX.ids[i]
    if id ~= nil then
      pcall(function()
        -- 先问一下还活着没：对已播完的实例调 StopAudio 在部分实现里会抛错
        local alive = true
        if game.IsAudioAlive ~= nil then
          local okAlive, a = pcall(game.IsAudioAlive, id)
          if okAlive then alive = a and true or false end
        end
        if alive then game.StopAudio(id) end
      end)
    end
  end
  SFX.ids = {}
  SFX.count = 0
  SFX.head = 0
end

-- 播一个音效。
-- 【参数写法】接受 CONFIG.SFX 的键名，**大小写不敏感**：`sfx_play("move")` 与
--   `sfx_play("MOVE")` 等价。理由：CONFIG.SFX 的键按平台习惯用大写，
--   而调用点写小写更贴近 Demo 的 `SFX.play("move")` 语义（也便于
--   tools_work/consistency_check.cjs 用同一条正则同时核对两边）。
--   实现上先查原样，再查大写，两次哈希查找，开销可忽略。
-- 返回实例 ID（成功）或 nil（关闭/失败/无此键）。
local function sfx_play(name)
  if not SFX.enabled then return nil end
  if SFX.available == false then return nil end        -- 已确认平台没有此能力，直接跳过
  local id = CONFIG.SFX[name]
  if id == nil then
    local upper = string.upper(tostring(name))
    id = CONFIG.SFX[upper]
  end
  -- 【未知键名必须留痕】这里原先直接 `if id == nil then return nil end`，于是键名写错
  -- （例如把 GAME_END 写成 "over"）会**完全静默**：不播、不报错、不写日志，
  -- 只有靠人把调用点逐个对回表才能发现。实测就踩过一次（终局音永远不响）。
  -- 现在改成打一次错误日志并禁用该项，绝不静默。
  if id == nil then
    local key = tostring(name)
    if not SFX.badKeyLogged[key] then
      SFX.badKeyLogged[key] = true
      log_err("音效键名不存在：%s（CONFIG.SFX 里没有这个键，该音效不会播放）", key)
    end
    return nil
  end
  if id == 0 then return nil end                       -- 明确配置为 0 = 关闭，这是合法状态

  -- 【能力探测只做一次】第一次调用时就确定 PlayAudio2D 是否存在，
  -- 之后按 available 走，不再反复 pcall 一个必然失败的东西。
  local ok, instId = pcall(function() return game.PlayAudio2D(id) end)
  if not ok then
    SFX.available = false
    if not SFX.failLogged then
      SFX.failLogged = true
      log_err("音效不可用（game.PlayAudio2D 调用失败），已自动降级为静音：%s", tostring(instId))
    end
    return nil
  end
  SFX.available = true
  -- PlayAudio2D 可能返回 nil（静音环境/资源未配置），此时没有实例可记，不算错
  if type(instId) == "number" then sfx_remember(instId) end
  return instId
end

-- 音效开关：翻转并返回新状态
local function sfx_toggle()
  SFX.enabled = not SFX.enabled
  if not SFX.enabled then
    -- 关掉时立即停掉正在播的（否则「音效：关」之后还能听到结束音拖尾，观感很怪）
    sfx_stop_all()
  else
    -- 开回来时给一次确认音，让用户知道确实开了
    sfx_play("select")
  end
  return SFX.enabled
end

