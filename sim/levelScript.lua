-- 高亮的呼吸/脉冲（v1.7）
-- -----------------------------------------------------------------------------
-- 静态色块看起来「死板」，加一层极轻微的尺寸与色深脉动，画面立刻活起来。
-- 全部按 ANIM.clock 算相位，不再单独累计时间：
--   选中格  → 0.95s 周期，尺寸 1.00↔1.02，透明度跟随正弦
--   落点圆点 → 1.15s 周期，尺寸 1.00↔1.12，同相位错开（读起来像一圈点子在闪）
-- 每帧只改仍可见的那几个，落点最多 28 个，开销可忽略。
-- 【注意类型】selHL 是文本框（bgColor），legalHL 池是图片控件（imageColor），
--   两种控件的颜色字段名不同，写错会抛 "no such field"（模拟器实测踩到）。
-- =============================================================================
local function anim_update_hilites(dt)
  if not GAME.animated then return end
  local t = ANIM.clock
  local L = UI.L

  -- 选中格：薄罩脉冲（尺寸几乎不变，主要让透明度呼吸出来）
  if UI.selHL ~= nil and UI.selHL.active and UI.selHLx ~= nil then
    local ph = (t % CONFIG.ANIM.SELECT_PULSE) / CONFIG.ANIM.SELECT_PULSE
    local s = math.sin(ph * math.pi * 2)
    local side = L.cell * (1 + s * 0.018)
    UI.selHL:SetSizeDelta(side, side)
    UI.selHL:SetAnchoredPosition(UI.selHLx - (side - L.cell) / 2,
                                 UI.selHLy - (side - L.cell) / 2)
    UI.selHL.bgColor = color_alpha(CONFIG.COLOR.SEL_HL, 0.80 + s * 0.20)
    -- 上下亮框跟着薄罩一起呼吸（只改宽度，竖向位置随薄罩边缘）
    if UI.selRingTop ~= nil and UI.selRingTop.active then
      UI.selRingTop:SetSizeDelta(side, UI.selRingW)
      UI.selRingTop:SetAnchoredPosition(UI.selHLx - (side - L.cell) / 2,
                                        UI.selHLy + side - UI.selRingW)
      UI.selRingTop.bgColor = color_alpha(CONFIG.COLOR.SEL_RING_A, 0.80 + s * 0.20)
      UI.selRingBot:SetSizeDelta(side, UI.selRingW)
      UI.selRingBot:SetAnchoredPosition(UI.selHLx - (side - L.cell) / 2, UI.selHLy)
      UI.selRingBot.bgColor = color_alpha(CONFIG.COLOR.SEL_RING_B, 0.80 + s * 0.20)
    end
  end

  -- 落点：错相位呼吸
  -- 【v1.11】hlBase 现在存的是**中心点**（图片控件 pivot=0.5），所以缩放时位置不变，
  -- 只改尺寸即可 —— 中心不动的缩放。旧代码还额外减了 (d - b.size)/2，
  -- 那是「按左下角定位」的补偿，在中心定位下会让圆点每帧往左下漂一点。
  local used = UI.legalHLUsed or 0
  local base = ANIM.hlBase
  if base == nil then return end
  for i = 1, used do
    local c = UI.legalHL[i]
    local b = base[i]
    if c ~= nil and b ~= nil and c.active then
      local ph = ((t + i * 0.09) % CONFIG.ANIM.LEGAL_PULSE) / CONFIG.ANIM.LEGAL_PULSE
      local k = 1 + math.sin(ph * math.pi * 2) * 0.12
      local d = b.size * k
      c:SetSizeDelta(d, d)
      c:SetAnchoredPosition(b.x, b.y)
    end
  end
end

