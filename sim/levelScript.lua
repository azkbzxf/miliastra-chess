-- 走子记录文本：白 e2→e4

local function move_text(mv, side)
  local function sqname(sq)
    return string.char(string.byte("a") + (sq % 8)) .. tostring((sq // 8) + 1)
  end
  local prefix = (side == WHITE) and "白 " or "黑 "
  local s = prefix .. sqname(mv.from) .. "→" .. sqname(mv.to)
  if mv.promo then
    local chars = { [QUEEN] = "=Q", [ROOK] = "=R", [BISHOP] = "=B", [KNIGHT] = "=N" }
    s = s .. chars[mv.promo]
  end
  return s
end

-- 应用一步棋（含吃子记录、走子记录、棋钟加秒、终局判定）
--
-- 【v1.7 动画接入：必须在 RULES.make 之前抓槽位】
--   make 之后棋盘的 e2 已经空了、e4 已经是自己的子，再靠格号找「被移动的那一枚」会
--   找到自己刚放上去的那一格。所以顺序是：
--     ① 先按 from/to 抓出「要走的那枚」与「要吃的那些」槽位
--     ② make 改状态
--     ③ 渲染（此时槽位的 sq 已失效，会自动重绑到正确格）
--     ④ 用 ① 抓到的槽位对象播放移动 / 淡出动画
--   槽位一旦抓到手，后续重绑不影响它（动画只改 slot.x/y/scale）。
local function apply_move(mv)
  local side = GAME.st.turn
  local captured = GAME.st.board[mv.to]
  local capSq = mv.to
  if mv.ep then
    capSq = shift(mv.to, side == WHITE and -1 or 1, 0)
    captured = GAME.st.board[capSq]
  end

  -- ① 动画前置：抓槽位（此时棋盘还是「走之前」的状态）
  local movingSlot = nil
  local capturedSlot = nil
  if GAME.animated and GAME.uiReady then
    movingSlot = slot_at(mv.from)
    if captured ~= 0 then
      capturedSlot = slot_at(capSq)
      -- 王车易位时车也要动：车的槽位在另一侧角上
    end
  end

  RULES.make(GAME.st, mv)

  -- 吃子记录
  if captured ~= 0 then
    local letter = PIECE_LETTER[captured]
    if captured > 0 then
      GAME.capturedWhite[#GAME.capturedWhite + 1] = letter
    else
      GAME.capturedBlack[#GAME.capturedBlack + 1] = letter
    end
  end

  -- 走子记录
  GAME.moveLog[#GAME.moveLog + 1] = move_text(mv, side)
  GAME.lastFrom = mv.from
  GAME.lastTo = mv.to
  GAME.turnCount = GAME.turnCount + 1

  -- 棋钟加秒（走子方 +INCREMENT）
  if side == WHITE then
    GAME.clockWhite = GAME.clockWhite + CONFIG.INCREMENT_SEC
  else
    GAME.clockBlack = GAME.clockBlack + CONFIG.INCREMENT_SEC
  end

  -- 【复盘快照】每走一步追加一项，供复盘逐手回放（v1.6）
  -- 只存最小信息：走完后的 FEN + 该步文案 + 起终点 + 双方失子数 + 双方棋钟。
  -- 局面表在复盘翻页时才 parse，不在逐帧里做。
  GAME.history[#GAME.history + 1] = {
    fen = RULES.fen_of(GAME.st),
    text = GAME.moveLog[#GAME.moveLog],
    from = mv.from, to = mv.to,
    capW = #GAME.capturedWhite, capB = #GAME.capturedBlack,
    clockW = GAME.clockWhite, clockB = GAME.clockBlack,
  }

  -- ② 先播「被吃」的淡出（它已经不属于棋盘，渲染不会碰它）
  if capturedSlot ~= nil then anim_capture_piece(capturedSlot) end

  -- 终局判定
  local status = RULES.game_status(GAME.st)
  if status.over then
    GAME.over = true
    if status.result == "1-0" then
      GAME.resultText = CONFIG.TEXT.RESULT_WHITE_WIN
      GAME.resultSub = (status.reason == "checkmate") and CONFIG.TEXT.SUB_CHECKMATE
        or CONFIG.TEXT.SUB_RESIGN_BLACK
    elseif status.result == "0-1" then
      GAME.resultText = CONFIG.TEXT.RESULT_BLACK_WIN
      GAME.resultSub = (status.reason == "checkmate") and CONFIG.TEXT.SUB_CHECKMATE
        or CONFIG.TEXT.SUB_RESIGN_WHITE
    else
      -- 【键名修正】这里原先写的是 RESULT_DRAW_AGREED_AGREED（多打了一个 _AGREED），
      -- CONFIG.TEXT 里并不存在该键 → 取到 nil → 结算标题为空（模拟器实测：和棋结算标题空白）。
      -- 正确键是 RESULT_DRAW_AGREED。和棋标题按下法分档：逼和/五十步/三次重复/子力不足各有专名。
      if status.reason == "stalemate" then GAME.resultText = CONFIG.TEXT.RESULT_STALEMATE
      elseif status.reason == "fifty" then GAME.resultText = CONFIG.TEXT.RESULT_FIFTY
      elseif status.reason == "threefold" then GAME.resultText = CONFIG.TEXT.RESULT_THREEFOLD
      elseif status.reason == "insufficient" then GAME.resultText = CONFIG.TEXT.RESULT_INSUFFICIENT
      else GAME.resultText = CONFIG.TEXT.RESULT_DRAW_AGREED end
      if status.reason == "stalemate" then GAME.resultSub = CONFIG.TEXT.SUB_STALEMATE
      elseif status.reason == "fifty" then GAME.resultSub = CONFIG.TEXT.SUB_FIFTY
      elseif status.reason == "threefold" then GAME.resultSub = CONFIG.TEXT.SUB_THREEFOLD
      elseif status.reason == "insufficient" then GAME.resultSub = CONFIG.TEXT.SUB_INSUFFICIENT
      else GAME.resultSub = CONFIG.TEXT.SUB_DRAW_AGREED end
    end
  end

  clear_highlights()

  -- ③ 渲染新局面前，先把「被移动的那枚」临时挂到目标格上（不让它被当成新子就地瞬移）
  if movingSlot ~= nil then
    movingSlot.sq = mv.to
    movingSlot.key = GAME.st.board[mv.to]
    -- 易位：王走两格时，车也要动
  end

  render_all()

  -- ④ 播移动动画（渲染之后，画面上已经是「棋子出现在目标格」的状态，
  --    但 slot.x/y 还是起点，下一帧就从这个位置补间过去）
  if movingSlot ~= nil then
    anim_move_piece(movingSlot, mv.from, mv.to, nil)
  end

  -- ⑤ 音效（v1.10）。顺序与优先级完全照 Demo（chess_demo.html 第 2002-2009 行）：
  --   走子/吃子先出声，将军与终局是「更重要的信息」，覆盖在后面再响一次。
  --   【易位只播 CASTLE 不播 MOVE】易位本质也是走子，但 Demo 的语义是「两步一起动」，
  --   播普通走子音会让人觉得「还有一枚没走」；所以易位走独立的更重的那一声。
  --   【联机回声不出声】对方走子经 net_on_signal 也会进 apply_move，
  --   若不加标记，同一手棋会在两端各响一次（本端 + 收到广播那一端各响）——
  --   但这里其实两端各响一次是**对的**（各自玩家都在自己屏幕上看到这步），
  --   所以不做回声过滤，与 Demo 的 fromRemote 语义保持一致即可（Demo 也是远端不出声，
  --   因为它模拟的是同一台机器双窗口；真机上两端是两个玩家，各响一次才对）。
  if mv.castle then
    sfx_play("castle")
  elseif captured ~= 0 then
    sfx_play("capture")     -- 吃子优先于走子（同一手只响一声）
  else
    sfx_play("move")
  end

  local nowInCheck = (not GAME.over) and RULES.in_check(GAME.st, GAME.st.turn)
  if nowInCheck then sfx_play("check") end
  -- 【终局音放到 show_result 里统一播】apply_move 只是一条到达终局的路径，
  -- 认输 / 超时 / 和棋 / 联机收到对方认输都不经过这里。统一在 show_result 播，
  -- 配合 SFX.overFired 保证「任何路径都只响一次」。见 show_result 的实现。
  if status.over then show_result() end
end

-- 正常模式的面板按钮（新开/认输/求和/同屏）显隐
-- 【为什么必须定义在 show_result 之前】show_result / hide_result / show_confirm 都要用它
-- 锁/解锁面板。Lua 是**词法作用域**：函数体在「定义那一刻」就确定名字绑定，不是运行时才查。
-- 所以只要 show_result（更早）的函数体里出现 show_panel_buttons，就必须让这个名字在它之前
-- 已经是 local —— 否则会被绑成 global，运行时是 nil。
-- 【踩过的坑】曾把它移到 hide_result 之前就以为够了，漏了更早的 show_result，
-- 结果所有终局路径（认输/将死/超时/和棋）全部崩在
-- `attempt to call a nil value (global 'show_panel_buttons')`，结算面板弹不出来。
-- lua_check.cjs 的「局部函数无先用后定义」检查抓到了它。
local function show_panel_buttons(on)
  ui_set_active(UI.panel.btnNew, on)
  ui_set_active(UI.panel.btnResign, on)
  ui_set_active(UI.panel.btnDraw, on)
  ui_set_active(UI.panel.btnLocal, on)
  ui_set_active(UI.panel.hitNew, on)
  ui_set_active(UI.panel.hitResign, on)
  ui_set_active(UI.panel.hitDraw, on)
  ui_set_active(UI.panel.hitLocal, on)
end

function show_result()
  if not GAME.uiReady then return end
  -- 【终局音的唯一播放入口】所有到达终局的路径（将死/逼和/五十步/三次重复/子力不足/
  -- 认输/超时/和棋同意/联机收到对方认输）最后都会调 show_result，在这里播最省心。
  -- SFX.overFired 保证只响一次：结算面板可能被重复打开（例如退出复盘会再弹一次）。
  if not SFX.overFired then
    SFX.overFired = true
    -- 【键名必须是 GAME_END，不是 "over"】CONFIG.SFX 里的终局音效键叫 GAME_END；
    -- Demo 侧写的是 SFX.play("over")，照抄过来会取到 nil → 静默不播（不报错、不写日志）。
    -- sfx_play 虽做了 string.upper 回退，但 "over" 大写仍是 "OVER"，依然匹配不到 GAME_END。
    sfx_play("GAME_END")
  end
  UI.result.title.text = GAME.resultText or ""
  -- 结算说明行里的 {t} 用实际对局用时填充（docs/策划案.md 9.4）
  local sub = GAME.resultSub or ""
  if string.find(sub, "{t}", 1, true) then
    local elapsed = math.floor(GAME.elapsedSec or 0)
    local mm = elapsed // 60
    local ss = elapsed % 60
    sub = string.gsub(sub, "{t}", string.format("%02d:%02d", mm, ss))
  end
  UI.result.sub.text = sub
  ui_set_active(UI.result.overlay, true)
  -- 先开投影/描边再开面板底，保证层级顺序（同级后开启的在上，但控件本身是按创建顺序叠的）
  ui_set_active(UI.result.shadow, true)
  ui_set_active(UI.result.edgeBox, true)
  ui_set_active(UI.result.bg, true)
  ui_set_active(UI.result.title, true)
  ui_set_active(UI.result.sub, true)
  ui_set_active(UI.result.btnAgain, true)
  ui_set_active(UI.result.hitAgain, true)
  ui_set_active(UI.result.btnReview, true)
  ui_set_active(UI.result.hitReview, true)
  ui_set_active(UI.result.hitOverlay, true)
  -- 终局后锁棋盘输入
  for sq = 0, 63 do
    if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], false) end
  end
  -- 【v1.10 修：结算面板同样要锁面板按钮】
  -- 与确认弹窗同一个问题：面板命中区被 raise_hit 抬到了结局面板之上，视觉被盖住但
  -- 仍可点击。其中「求和」在终局后只是弹个提示、危害有限，但「切换本地同屏」会
  -- 重置对局状态 —— 用户点了结算面板上的按钮却被底下那个接走，属于同一类穿透。
  -- 这里统一关掉，结算期间只留结算面板自己的两个键（再来一局 / 复盘）。
  show_panel_buttons(false)
  ui_set_active(UI.panel.hitSfx, false)
  ui_set_active(UI.review.hitToggle, false)
end

local function hide_result()
  ui_set_active(UI.result.overlay, false)
  ui_set_active(UI.result.shadow, false)
  ui_set_active(UI.result.edgeBox, false)
  ui_set_active(UI.result.bg, false)
  ui_set_active(UI.result.title, false)
  ui_set_active(UI.result.sub, false)
  ui_set_active(UI.result.btnAgain, false)
  ui_set_active(UI.result.hitAgain, false)
  ui_set_active(UI.result.btnReview, false)
  ui_set_active(UI.result.hitReview, false)
  ui_set_active(UI.result.hitOverlay, false)
  -- 【v1.10 修】对应 show_result 里的面板锁定，这里恢复。
  -- 只有「对局仍在进行」时才恢复：结算后点「再来一局」会先 new_game() 再 hide_result()，
  -- 此时 GAME.over 已被 new_game 置回 false，所以正常；而启动时 hide_result 只是做初始
  -- 隐藏，那时面板按钮由 build 流程自己管理，这里以 GAME.over 为界不会误开。
  if not GAME.over and GAME.confirmKind == nil and GAME.review == nil then
    show_panel_buttons(true)
    ui_set_active(UI.panel.hitSfx, true)
    ui_set_active(UI.review.hitToggle, true)
  end
end

