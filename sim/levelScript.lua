  -- build_board 之后建的棋子图元 / 高亮层是同级后出现的节点，会盖在命中区之上挡住点击
  -- （模拟器实测：不提升则棋盘完全点不动）。
  for sq = 0, 63 do
    local c = UI.hitAreas[sq]
    if c ~= nil then pcall(function() c:SetAsLastSibling() end) end
  end
end

