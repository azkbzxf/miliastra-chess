-- 画一枚棋子到一个槽位。slot.prims 是固定容量池，播放期只改不建。
--
-- 【v1.11 层序（去掉了底部投影，issue #1 第 5 条）】
--   ① 外形描边：全部形体形状各自外扩 pad，画描边色
--   ② 外形填充：全部形体形状按原尺寸，画体色
--   ③ 镂空描边：镂空形状外扩 pad，画描边色（让眼窝等有边）
--   ④ 镂空填充：镂空形状按原尺寸，画**棋格色**（视觉上等于挖穿）
--   ⑤ 细节线：role2，对比色，原尺寸
--
-- 为什么描边不逐个形状画：逐形画会在棋子内部相邻形状交界处画出线，
-- 变成「一堆叠起来的积木」。整组放大再整组缩小，只有最外廓出现描边。
--
-- 【v1.11 性能】image_apply 加了「值相同就不写控件」的短路，见该函数的说明。
-- 本函数每帧被脏槽位重绘调用时，同一枚棋子的形状数据是不变的 ——
-- 只有随动画变化的尺寸/位置需要写，其余（图元、颜色、旋转）全部命中缓存跳过。
--
-- scale：动画用的整体缩放（1 = 原大），缩放中心是棋子方框中心
-- dy   ：动画用的额外竖直偏移（画布单位）
local function paint_slot(slot, p, bx, by, sq, scale, dy)
  local L = UI.L
  local box = L.cell
  local side = box * 0.92
  scale = scale or 1
  dy = dy or 0

  if slot.prims == nil then return end

  local art = piece_art_of(p)
  local cap = #slot.prims
  local n = 0
  -- 可见性缓存：slot.shown[k] = 该图元当前是否已激活。挂在槽位表上（不是控件上），
  -- 因为平台控件对象不保证允许写自定义字段。
  local shown = slot.shown
  if shown == nil then
    shown = {}
    slot.shown = shown
  end

  local function take()
    n = n + 1
    if n > cap then return nil end
    return slot.prims[n]
  end

  local function next_visible()
    local c = take()
    if c ~= nil then
      -- 【性能】只有从隐藏变可见时才写 active/visible；槽位复用时这个分支很少命中。
      -- 可见性标记放在槽位自己的表里（slot.shown[k]），不写到平台控件对象上。
      if not shown[n] then
        shown[n] = true
        ui_set_active(c, true)
      end
    end
    return c
  end

  if art == nil then
    for k = 1, cap do
      if shown[k] then shown[k] = false; ui_set_active(slot.prims[k], false) end
    end
    return
  end

  local fill, edge = piece_colors(p)

  -- 缩放后的棋子方框：中心不动，边长 × scale
  -- 【视觉居中】+ piece_center_dy() * sside：把形状并集的竖向中心对到格中心（见该函数说明）
  local sside = side * scale
  local ox = bx + (box - sside) / 2
  local oy = by + (box - sside) / 2 + dy + piece_center_dy() * sside

  -- 【描边：每个形状各自向外长 t，而不是整组等比放大】
  --
  -- 这里走过一段弯路，把两个方案写清楚，避免再反复：
  --
  -- 方案 A（试过，弃用）：整组形状绕棋子方框中心等比放大 (1+k)。
  --   问题：离中心越远的形状，放大后外移越多。于是同一枚棋子，
  --   远离中心的那一侧描边粗、靠近中心的一侧细 —— 一圈边粗细不均，看起来"发胖"。
  --
  -- 方案 B（现在用）：每个形状自己向外长 t，中心不动。
  --   描边层 = 全部形状各自向外扩 t；填充层 = 原尺寸。
  --   两层之差正好是「并集整体向外偏 t」，也就是一圈**均匀**的描边。
  --   对单个形状这是精确的；对并集只在形状之间的凹角处略厚一点，
  --   在 1px 量级完全看不出来。
  --
  -- 还有一点要说明：形状之间本来就有宽窄差，外扩之后宽块仍比窄块宽 ——
  -- 这是**对的**，那正是原图的轮廓，不是需要消除的"台阶"。
  -- 真正会出"台阶"的是拿一串宽度递减的矩形去逼近曲线 —— 那种情况要靠改用椭圆/三角形，
  -- 而不是靠调整描边算法。
  --
  -- 【v1.11 细长形状夹一道上限】pad 是「方框比例的绝对量」，对 0.05 宽的鬃毛
  -- 相当于自身宽度的 80%，会把细节糊成色斑。所以再按短边比例夹一层（见 CONFIG 说明）。
  local padBase = CONFIG.PIECE_OUTLINE_PAD * sside
  local thinRatio = CONFIG.PIECE_PAD_THIN_RATIO
  local function pad_of(s)
    local limit = math.min(s[4], s[5]) * sside * thinRatio
    if limit < padBase then return limit end
    return padBase
  end

  -- ① 外形描边层：**全部形状先画一遍描边**，② 再全部画一遍填充
  --
  -- 【顺序绝不能改成交替画（会出大事）】
  --   若改成「形状 A 的描边 + A 的填充 → 形状 B 的描边 + B 的填充 → …」，
  --   那么 B 的描边就会压在 A 的填充之上，棋子内部每两个形状的交界处都会出现一道描边色，
  --   整枚棋子变成「一堆描好的积木叠起来」，冠尖/鬃毛上还会戳出一圈黑边
  --   （v1.11 第一版实测：白王头上长出几个黑色三角、黑车身上出现白色描边缝）。
  --   必须是「所有描边 → 所有填充」两遍，描边层才只在**并集外缘**露出来。
  for _, s in ipairs(art) do
    if s[7] == 0 then
      local pad = pad_of(s)
      local c = next_visible()
      if c == nil then break end
      image_apply(c, prim_asset(s[1]), edge, s[6])
      cw(); c:SetSizeDelta(s[4] * sside + pad * 2, s[5] * sside + pad * 2)
      cw(); c:SetAnchoredPosition(ox + s[2] * sside, oy + s[3] * sside)
    end
  end
  for _, s in ipairs(art) do
    if s[7] == 0 then
      local c = next_visible()
      if c == nil then break end
      image_apply(c, prim_asset(s[1]), fill, s[6])
      cw(); c:SetSizeDelta(s[4] * sside, s[5] * sside)
      cw(); c:SetAnchoredPosition(ox + s[2] * sside, oy + s[3] * sside)
    end
  end

  -- ③ 镂空描边层 + ④ 镂空填充层：同样「先全部描边、再全部填充」
  -- 【镂空填充用棋格色】平台图元没有挖洞能力，只能「用底色再画一遍同一形状」。
  -- 注意这个色依赖于该格明暗，所以带镂空的棋子走到另一种颜色的格子上时必须重绘 ——
  -- image_apply 的颜色缓存不会误判（颜色真的变了）。
  local sqIsDark = ((sq // 8) + (sq % 8)) % 2 == 0
  local holeColor = sqIsDark and CONFIG.COLOR.SQ_DARK or CONFIG.COLOR.SQ_LIGHT
  for _, s in ipairs(art) do
    if s[7] == 1 then
      local pad = pad_of(s)
      local c = next_visible()
      if c == nil then break end
      image_apply(c, prim_asset(s[1]), edge, s[6])
      cw(); c:SetSizeDelta(s[4] * sside + pad * 2, s[5] * sside + pad * 2)
      cw(); c:SetAnchoredPosition(ox + s[2] * sside, oy + s[3] * sside)
    end
  end
  for _, s in ipairs(art) do
    if s[7] == 1 then
      local c = next_visible()
      if c == nil then break end
      image_apply(c, prim_asset(s[1]), holeColor, s[6])
      cw(); c:SetSizeDelta(s[4] * sside, s[5] * sside)
      cw(); c:SetAnchoredPosition(ox + s[2] * sside, oy + s[3] * sside)
    end
  end

  -- ⑤ 细节线（cburnett 风格专属，role=2）
  -- 这是 en-croissant 那套棋子的灵魂：车身的砖缝、后的冠弧、王的冠带、象的十字、
  -- 马的鬃线、兵的颈线。它们用**对比色**画（白子画深线、黑子画浅线），
  -- 尺寸就用数据本身的宽高 —— 不外扩，因为细节线不是轮廓，外扩会变成一道粗纹。
  -- 绘制顺序放在最后：细节线永远压在填充层之上，否则会被前面的形状盖掉。
  local detailColor = edge   -- 白子：描边色=深色；黑子：描边色=浅色 → 正好是对比色
  for _, s in ipairs(art) do
    if s[7] == 2 then
      local c = next_visible()
      if c == nil then break end
      image_apply(c, prim_asset(s[1]), detailColor, s[6])
      cw(); c:SetSizeDelta(s[4] * sside, s[5] * sside)
      cw(); c:SetAnchoredPosition(ox + s[2] * sside, oy + s[3] * sside)
    end
  end

  -- 多余图元隐藏（容量池比实际用量大时）
  for k = n + 1, cap do
    if shown[k] then shown[k] = false; ui_set_active(slot.prims[k], false) end
  end
end

-- 把一个槽位的所有图元隐藏
local function hide_slot(slot)
  if slot == nil or slot.prims == nil then return end
  local shown = slot.shown
  for k = 1, #slot.prims do
    if shown == nil or shown[k] then
      if shown ~= nil then shown[k] = false end
      ui_set_active(slot.prims[k], false)
    end
  end
end

-- 棋子渲染（v1.7：槽位稳定绑定 + 平滑移动）
--
-- 【为什么要「稳定绑定」而不是每帧按下标重排】
--   旧实现是「按 sq 顺序把棋子塞进 slot[1..n]」，走一步棋之后所有槽位的
--   归属都会变，于是想给「被移动的那一枚」做补间就无从下手 —— 只能整盘重画，
--   看起来就是棋子瞬间跳过去。现在改成：槽位一旦绑定某个棋子身份就保持不动
--   （slot.sq 记录当前所在格），只在棋子被吃/升变时才解绑。
--   这样「从 e2 到 e4」就是同一个槽位改两个坐标，补间一次即可，棋子不会散架。
--
-- 【槽位身份】slot.key = 棋子符号（有符号棋子ID）；slot.sq = 当前格号；
--   slot.x / slot.y = 当前实际绘制位置（动画推进时逐帧改写）；
--   slot.sx / slot.sy = 目标位置（渲染目标）。
--   动画只改 x/y，不重新解算形状，所以 32 枚一起动也不掉帧。
local function slot_bind(slot, p, sq)
  slot.key = p
  slot.sq = sq
end

local function render_pieces(onlySlots, onlyCount)
  if not GAME.uiReady then return end
  if UI.pieceSlots == nil or UI.pieceSlots[1] == nil then return end

  local board = view_board()
  local L = UI.L

  -- ===== 快速路径：只重绘指定的槽位（v1.10 提速）=====
  -- 【为什么需要这条路径】动画期间 OnUpdate 每帧调一次 render_pieces()，
  -- 全量路径要「重建 bySq（64 格 + 32 槽）→ 遍历 32 槽 → 每槽 paint_slot」，
  -- 而 paint_slot 对一枚棋子要做 6 遍形状遍历、每个图元 3~4 次控件写。
  -- 32 枚 × 数十图元 ≈ 每帧数千次控件写 → 动画期间整体掉帧，手感就是「不跟手」。
  -- 但动画**只改一两个槽位**的 x/y/scale/lift，其余 30 枚这一帧根本没变，
  -- 重绘它们纯属浪费。所以动画分支只把「本帧真的变了」的槽位传进来。
  --
  -- 【为什么不漏绘】前提是「只有槽位自身字段变了才需要重绘」这条不变量成立：
  --   · 槽位归属（slot.sq / slot.key）只在 render_pieces 全量路径、apply_move、
  --     reset_piece_slots 里改，这三处之后都会走全量 render_pieces；
  --   · 动画任务（anim_move_piece / anim_capture_piece / board_intro）只改
  --     x / y / scale / lift / fading，不改归属。
  --   所以动画期间「归属」是稳定的，只有 x/y/scale/lift 在动 —— 只重绘这些槽位就够。
  --   动画跑完后 OnUpdate 还会补一帧**全量** render_pieces（见 OnUpdate 的 needsRepaint），
  --   把任何可能的残留（半格、旧位置）彻底刷干净。
  if onlySlots ~= nil then
    -- 注意：Lua 的 `#t` 对「带洞的表」不可靠，所以索引列表的长度由调用方显式给出
    -- （anim_take_dirty 返回的 dirtyCount）。缺省时退回 #onlySlots 兜底。
    local nSlots = onlyCount or #onlySlots
    ANIM.paintFramesPartial = ANIM.paintFramesPartial + 1
    for i = 1, nSlots do
      local slot = onlySlots[i]
      if slot ~= nil then
        if slot.sq ~= nil then
          if slot.x == nil then
            -- 理论上不会发生（动画开始前 slot.x 已由全量路径设好），兜底防崩
            slot.x, slot.y = LAYOUT.square_pos(L, slot.sq)
          end
          paint_slot(slot, slot.key, slot.x, slot.y - (slot.lift or 0),
                     slot.sq, slot.scale or 1, 0)
          ANIM.paintSlotsTotal = ANIM.paintSlotsTotal + 1
        elseif slot.fading then
          if slot.x ~= nil then
            paint_slot(slot, slot.key, slot.x, slot.y - (slot.lift or 0),
                       slot.fadeSq or 0, slot.scale or 1, 0)
            ANIM.paintSlotsTotal = ANIM.paintSlotsTotal + 1
          end
        end
      end
    end
    return
  end
  ANIM.paintFramesFull = ANIM.paintFramesFull + 1

  -- ① 建立「格号 → 槽位」映射，并把已经不在该格的槽位解绑
  local bySq = UI.slotBySq or {}
  for sq = 0, 63 do bySq[sq] = nil end
  for i = 1, CONFIG.PIECE_MAX_SLOTS do
    local slot = UI.pieceSlots[i]
    if slot ~= nil and slot.sq ~= nil then
      if board[slot.sq] ~= slot.key then
        slot.sq = nil; slot.key = nil      -- 这一枚已经不在原处（被吃/走掉）
      else
        bySq[slot.sq] = slot
      end
    end
  end

  -- ② 给还没占位的棋子分配空闲槽位
  for sq = 0, 63 do
    local p = board[sq]
    if p ~= 0 and bySq[sq] == nil then
      for i = 1, CONFIG.PIECE_MAX_SLOTS do
        local slot = UI.pieceSlots[i]
        if slot ~= nil and slot.sq == nil then
          slot_bind(slot, p, sq)
          local bx, by = LAYOUT.square_pos(L, sq)
          slot.x, slot.y = bx, by      -- 新出现的子直接就位（不补间）
          bySq[sq] = slot
          break
        end
      end
    end
  end
  UI.slotBySq = bySq

  -- ③ 逐槽位重绘（位置用 slot.x/slot.y，动画推进时它会被改写）
  local used = 0
  for i = 1, CONFIG.PIECE_MAX_SLOTS do
    local slot = UI.pieceSlots[i]
    if slot ~= nil and slot.sq ~= nil then
      used = used + 1
      if slot.x == nil then
        slot.x, slot.y = LAYOUT.square_pos(L, slot.sq)
      end
      paint_slot(slot, slot.key, slot.x, slot.y - (slot.lift or 0),
                 slot.sq, slot.scale or 1, 0)
    elseif slot ~= nil and slot.fading then
      -- 正在播放「被吃淡出」的槽位：继续画，直到动画播完自己隐藏
      if slot.x ~= nil then
        local sq = slot.fadeSq or 0
        paint_slot(slot, slot.key, slot.x, slot.y - (slot.lift or 0),
                   sq, slot.scale or 1, 0)
      end
    else
      hide_slot(slot)
    end
  end
  UI.slotShown = used
end

-- 找到当前落在某格的槽位（动画用）
local function slot_at(sq)
  if UI.slotBySq == nil then return nil end
  return UI.slotBySq[sq]
end

-- 平滑移动一枚棋子：fromSq → toSq，带弧线抬升 + 落子回弹。
-- 【为什么用弧线】直线横移看起来像「幻灯片」，加一点抛物线抬升后棋子像被拿起来放下。
-- 弧线用 sin(πu) 做钟形：两端为 0、中间最高，天然和起止对齐，不用额外配参数。
--
-- 【关键】slot.sq 在动画开始时**立刻改成 toSq**，而不是等落地才改。
--   原因：render_pieces 靠「slot.sq 上的棋子是否还是 slot.key」来判断槽位是否还有效，
--   并且只绘制有效槽位。若动画期间 sq 为 nil，这一枚会被判为无效直接隐藏，
--   于是「走子」看起来是原地消失 + 目标格冒出来，弧线动画根本看不到。
local function anim_move_piece(slot, fromSq, toSq, onDone)
  if slot == nil then return end
  local L = UI.L
  local x0, y0 = LAYOUT.square_pos(L, fromSq)
  local x1, y1 = LAYOUT.square_pos(L, toSq)
  local cell = L.cell
  local arc = CONFIG.ANIM.MOVE_ARC * cell
  local dur = CONFIG.ANIM.MOVE_DUR

  slot.sq = toSq          -- 立刻认领目标格（见上方说明）
  slot.x, slot.y = x0, y0 -- 绘制位置从起点开始
  slot.moving = true

  local ease = EASE.outCubic
  anim_add(dur, function(u)
    local e = ease(u)
    slot.x = x0 + (x1 - x0) * e
    slot.y = y0 + (y1 - y0) * e
    slot.lift = math.sin(u * math.pi) * arc
    -- 抬起时略微放大，落地回到原大（0.05 的呼吸量刚好不夸张）
    slot.scale = 1 + math.sin(u * math.pi) * 0.05
  end, function()
    slot.x, slot.y = x1, y1
    slot.lift = 0
    slot.moving = false
    -- 落子回弹：1.0 → 1+PEAK → 1.0
    -- SETTLE_NORM 把 sin(v·π)·(1-v) 的 0.579230 峰值归一，让视觉峰值真正等于 SETTLE_PEAK
    -- （见 CONFIG.ANIM.SETTLE_NORM 的说明；不归一会只弹到 4%，不是 Demo 的 7%）
    anim_add(CONFIG.ANIM.SETTLE_DUR, function(v)
      local k = 1 - v
      slot.scale = 1 + math.sin(v * math.pi) * k * CONFIG.ANIM.SETTLE_PEAK
                     * CONFIG.ANIM.SETTLE_NORM
    end, function()
      slot.scale = 1
      if onDone then onDone() end
    end, slot)   -- ← 回弹段也登记脏槽位
  end, slot)     -- ← 位移段登记脏槽位
end

-- 棋子被吃：原地缩小 + 上飘淡出。
-- 【为什么要 slot.fading】被吃掉的槽位已经脱离了棋盘归属（那一格现在是吃子的子），
--   render_pieces 会判它无效并隐藏。所以给它打个 fading 标记，让它继续被绘制，
--   直到动画播完再真正隐藏。
local function anim_capture_piece(slot)
  if slot == nil then return end
  slot.fadeSq = slot.sq      -- 挖洞色要用原格的明暗，先记下来
  slot.sq = nil
  slot.fading = true
  local s0 = slot.scale or 1
  local lift0 = slot.lift or 0
  anim_add(CONFIG.ANIM.CAPTURE_FADE, function(u)
    local k = 1 - u
    slot.scale = s0 * k * k
    slot.lift = lift0 + u * CONFIG.ANIM.MOVE_ARC * UI.L.cell * 0.8
  end, function()
    slot.fading = false
    slot.key = nil
    slot.fadeSq = nil
    slot.scale = 1
    slot.lift = 0
    hide_slot(slot)
  end, slot)   -- ← 淡出段登记脏槽位（fading 槽位也走局部重绘的 fading 分支）
end

-- 界面重建/重开时把槽位绑定全部清掉（避免新棋盘沿用旧槽位的动画中间态）
local function reset_piece_slots()
  for i = 1, CONFIG.PIECE_MAX_SLOTS do
    local slot = UI.pieceSlots[i]
    if slot ~= nil then
      hide_slot(slot)
      slot.sq = nil; slot.key = nil
      slot.x, slot.y = nil, nil
      slot.scale = 1
      slot.lift = 0
      slot.moving = false
      slot.fading = false
    end
  end
  UI.slotBySq = nil
  UI.slotShown = 0
end

local function render_captured()
  if not GAME.uiReady then return end
  local snap = review_snap()
  local cw, cb
  if snap ~= nil then
    cw = view_captured(GAME.capturedWhite, snap.capW)
    cb = view_captured(GAME.capturedBlack, snap.capB)
  else
    cw, cb = GAME.capturedWhite, GAME.capturedBlack
  end
  -- 【v1.11 文案】旧版是裸字母 "P P N"，看不出来是被谁吃掉的。现在带前缀。
  -- 【性能】文本只在真的变化时才写（平台写 text 会触发重新排版）。
  local function cap_text(list)
    if #list == 0 then return CONFIG.TEXT.CAP_NONE end
    return CONFIG.CAP_PREFIX .. table.concat(list, " ")
  end
  if UI.panel.capturedWhite then
    local txt = cap_text(cw)
    if UI.panel.capturedWhite.text ~= txt then UI.panel.capturedWhite.text = txt end
  end
  if UI.panel.capturedBlack then
    local txt = cap_text(cb)
    if UI.panel.capturedBlack.text ~= txt then UI.panel.capturedBlack.text = txt end
  end
end

