-- 棋盘命中区：复盘中一律锁死（复盘只看不点）
local function set_board_input(on)
  for sq = 0, 63 do
    if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], on) end
  end
end

-- 刷新复盘当前步的快照局面（翻页时只 parse 一次，缓存到 GAME.reviewState）
local function review_load(idx)
  local snap = GAME.history[idx + 1]
  if snap == nil then return false end
  GAME.review.idx = idx
  GAME.reviewState = RULES.parse_fen(snap.fen)
  return true
end

-- 进入复盘。停在最后一步（对局中看历史 / 结算后复盘都是这个默认）
local function enter_review()
  if #GAME.history <= 1 then
    -- 一步都没走，没得复盘
    if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.REVIEW_EMPTY end
    return false
  end
  GAME.review = { idx = 0 }
  review_load(#GAME.history - 1)
  -- 结算弹窗让位给复盘（退出复盘时会重新弹回来）
  hide_result()
  show_panel_buttons(false)
  show_review_buttons(true)
  ui_set_active(UI.review.btnToggle, true)
  ui_set_active(UI.review.hitToggle, true)
  UI.review.btnToggle.text = CONFIG.TEXT.BTN_REVIEW_EXIT
  set_board_input(false)
  clear_highlights()
  review_render()
  return true
end

-- 退出复盘：回到原局面。对局已结束则重新弹结算面板
local function exit_review()
  GAME.review = nil
  GAME.reviewState = nil
  show_review_buttons(false)
  show_panel_buttons(true)
  ui_set_active(UI.review.btnToggle, true)
  ui_set_active(UI.review.hitToggle, true)
  UI.review.btnToggle.text = CONFIG.TEXT.BTN_REVIEW_HISTORY
  if GAME.over then
    set_board_input(false)
    show_result()
  else
    set_board_input(true)
    if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.HINT_OPENING end
  end
  render_all()
end

-- 复盘翻页：delta=+1/-1 相对移动，target=绝对步（nil 表示不用）
local function review_goto(target, delta)
  if GAME.review == nil then return false end
  local idx = GAME.review.idx
  if target ~= nil then idx = target else idx = idx + delta end
  local maxIdx = #GAME.history - 1
  if idx < 0 then idx = 0 end
  if idx > maxIdx then idx = maxIdx end
  if idx == GAME.review.idx then return false end
  if not review_load(idx) then return false end
  review_render()
  return true
end

-- 复盘下的整屏重绘（与 render_all 同源，只是数据来自快照）
review_render = function()
  if not GAME.uiReady then return end
  local snap = review_snap()
  render_pieces()
  render_captured()
  render_move_log()
  update_clock_text()
  update_turn_text()
  show_last_move()
  show_check_warning()
  if UI.panel.hint then
    UI.panel.hint.text = (snap ~= nil and GAME.review.idx > 0)
      and tostring(snap.text) or CONFIG.TEXT.REVIEW_START_HINT
  end
end


-- 弹窗类型与文案映射（docs/策划案.md 9.5 C-01~C-04）
local CONFIRM_SPEC = {
  resign = { text = "CONFIRM_RESIGN",  yes = "CONFIRM_RESIGN_YES", no = "CONFIRM_RESIGN_NO" },
  newgame = { text = "CONFIRM_NEWGAME", yes = "CONFIRM_YES", no = "CONFIRM_NO" },
  switch = { text = "CONFIRM_SWITCH",  yes = "CONFIRM_YES", no = "CONFIRM_NO" },
  draw = { text = "CONFIRM_DRAW",      yes = "CONFIRM_DRAW_YES", no = "CONFIRM_DRAW_NO" },
}

local function show_confirm(kind)
  -- 【v1.10 修：重入护栏，优先级最高】
  -- 已有确认框开着时直接拒绝，不覆盖 confirmKind。
  -- 这一条是「防丢对局状态」的最后一道保险：即使 UI 锁失效（层级变化、新增按钮忘了锁、
  -- 联机信号在弹窗期间触发了别的 show_confirm），也不会把 resign 悄悄改成 newgame。
  -- 放在最前，早于任何 UI 写入 —— 被拒绝时界面保持原样，不会出现「文案已换、kind 没换」的半状态。
  if GAME.confirmKind ~= nil then return end
  local spec = CONFIRM_SPEC[kind] or CONFIRM_SPEC.newgame
  UI.confirm.text.text = CONFIG.TEXT[spec.text]
  UI.confirm.btnYes.text = CONFIG.TEXT[spec.yes]
  UI.confirm.btnNo.text = CONFIG.TEXT[spec.no]
  GAME.confirmKind = kind
  ui_set_active(UI.confirm.overlay, true)
  ui_set_active(UI.confirm.shadow, true)
  ui_set_active(UI.confirm.edgeBox, true)
  ui_set_active(UI.confirm.bg, true)
  ui_set_active(UI.confirm.text, true)
  ui_set_active(UI.confirm.btnYes, true)
  ui_set_active(UI.confirm.btnNo, true)
  ui_set_active(UI.confirm.hitYes, true)
  ui_set_active(UI.confirm.hitNo, true)
  -- 弹窗期间锁棋盘输入
  for sq = 0, 63 do
    if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], false) end
  end
  -- 【v1.10 修：弹窗期间必须锁面板按钮】
  -- 只锁棋盘是不够的。面板命中区在 build 末尾被 raise_hit 抬到了 confirmoverlay
  -- **之上**（overlay 只是视觉遮罩，不是命中区，挡不住点击），于是弹窗开着时
  -- 面板按钮照样点得动，能叠出第二个确认框。
  -- 而 confirmKind 是直接覆盖的，后果不是多弹一个框，而是**点「确定」执行错分支**：
  --   认输框开着 → 点「新开一局」→ confirmKind 变成 newgame → 点「确定」→ **重开一局**
  -- 用户以为在确认认输，实际把对局状态丢了。所以这里必须一并禁用。
  show_panel_buttons(false)
  -- 音效开关与复盘键不在 show_panel_buttons 里，单独锁
  ui_set_active(UI.panel.hitSfx, false)
  ui_set_active(UI.review.hitToggle, false)
end

-- 新开一局
local function new_game()
  GAME.st = RULES.parse_fen(START_FEN)
  GAME.over = false
  GAME.resultText = nil
  GAME.resultSub = nil
  GAME.clockWhite = CONFIG.INITIAL_TIME_SEC
  GAME.clockBlack = CONFIG.INITIAL_TIME_SEC
  GAME.moveLog = {}
  GAME.capturedWhite = {}
  GAME.capturedBlack = {}
  GAME.lastFrom = nil
  GAME.lastTo = nil
  GAME.turnCount = 0
  GAME.elapsedSec = 0
  GAME.pendingPromo = nil
  GAME.drawCooldown[1] = 0
  GAME.drawCooldown[2] = 0
  GAME.drawReqSent = false
  GAME.lastSentMove = nil
  -- 【复盘】新开一局清空历史，只留开局快照（history[1] 恒为开局）
  GAME.review = nil
  GAME.reviewState = nil
  GAME.history = { {
    fen = RULES.fen_of(GAME.st),
    text = "",
    from = nil, to = nil,
    capW = 0, capB = 0,
    clockW = CONFIG.INITIAL_TIME_SEC, clockB = CONFIG.INITIAL_TIME_SEC,
  } }
  clear_highlights()
  hide_result()
  hide_promo()
  hide_confirm()
  -- 【音效】新开一局要：
  --   ① 停掉正在播的实例（上一局的 GAME_END 有 6 秒长，不停会串到新局开场）
  --   ② 复位三个「只播一次」的标记，否则新局的终局音和低时提示永远不会响
  sfx_stop_all()
  SFX.overFired = false
  SFX.lowTimeFired[1] = false
  SFX.lowTimeFired[2] = false
  -- 【动画】清掉正在跑的所有动画，并把槽位绑定复位（否则新棋盘会沿用旧槽位的中间态）
  anim_clear()
  if GAME.uiReady then reset_piece_slots() end
  -- 复盘按钮回到正常态（新开一局总是回到对局模式）
  if GAME.uiReady and UI.review then
    show_review_buttons(false)
    show_panel_buttons(true)
    ui_set_active(UI.review.btnToggle, true)
    ui_set_active(UI.review.hitToggle, true)
    UI.review.btnToggle.text = CONFIG.TEXT.BTN_REVIEW_HISTORY
  end
  if GAME.uiReady then
    for sq = 0, 63 do
      if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], true) end
    end
    if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.HINT_OPENING end
  end
  render_all()
  -- 【动画】开局「逐格弹入」：每个棋子按格号错开一点点出现，整盘像被摆上来
  if GAME.animated and GAME.uiReady then board_intro() end
end

-- 开局弹入动画：按「从下往上、从左到右」的顺序把 32 枚棋子依次弹出来。
-- 【为什么用 scale 弹入而不是淡入】图元控件的 imageColor 是乘色，改 alpha 时
-- 半透明叠加会露出底下的格色，看起来像脏点；缩放弹入则始终不透明，干净。
function board_intro()
  if not GAME.uiReady then return end
  local idx = 0
  for i = 1, CONFIG.PIECE_MAX_SLOTS do
    local slot = UI.pieceSlots[i]
    if slot ~= nil and slot.sq ~= nil then
      local st = idx * CONFIG.ANIM.INTRO_STAGGER
      idx = idx + 1
      slot.scale = 0.01
      slot.lift = 0
      anim_add(st, function(u)
        -- 延迟段：什么也不做，只是等
        slot.scale = 0.01
      end, function()
        anim_add(CONFIG.ANIM.BOARD_INTRO * 0.42, function(v)
          -- outBack：略微超过 1 再回来，像被「放」到格子上
          slot.scale = math.max(0.01, EASE.outBack(v))
        end, function()
          slot.scale = 1
        end, slot)   -- ← 弹入段登记脏槽位
      end, slot)     -- ← 延迟段也登记（否则延迟期间该槽位不重绘，会停在上一帧的 scale）
    end
  end
end

-- 选中一枚子
local function select_square(sq)
  local st = GAME.st
  local p = st.board[sq]
  if p == 0 then return false end
  -- 只能选自己一方的子
  if (p > 0) ~= (st.turn == WHITE) then return false end
  -- 联机模式下只能操作自己那一方
  if not GAME.localMode then
    local myTurn = (GAME.mySide == 1 and st.turn == WHITE) or (GAME.mySide == 2 and st.turn == BLACK)
    if not myTurn then return false end
  end

  local moves = RULES.legal_moves(st)
  local targets = {}
  local mine = {}
  for _, mv in ipairs(moves) do
    if mv.from == sq then
      mine[#mine + 1] = mv
      targets[mv.to] = true
    end
  end
  if #mine == 0 then return false end

  GAME.selected = sq
  GAME.legalTargets = targets
  GAME.legalMoves = mine

  local L = UI.L

  -- 选中格：琥珀薄罩 + 上下两条亮边框
  local x, y = LAYOUT.square_pos(L, sq)
  UI.selHLx, UI.selHLy = x, y
  UI.selHL:SetSizeDelta(L.cell, L.cell)
  UI.selHL:SetAnchoredPosition(x, y)
  UI.selHL.bgColor = color_of(CONFIG.COLOR.SEL_HL)
  ui_set_active(UI.selHL, true)
  local rt = UI.selRingW
  UI.selRingTop:SetSizeDelta(L.cell, rt)
  UI.selRingTop:SetAnchoredPosition(x, y + L.cell - rt)
  ui_set_active(UI.selRingTop, true)
  UI.selRingBot:SetSizeDelta(L.cell, rt)
  UI.selRingBot:SetAnchoredPosition(x, y)
  ui_set_active(UI.selRingBot, true)

  -- 落点高亮：空格画圆点、可吃子画整格薄罩（都记下基准位置给脉动用）
  --
  -- 【v1.11 修 issue #1 第 1 条「走棋特效错位严重」】
  -- 这里的控件来自 `create_image`，它的 pivot 是 **0.5**（图元要绕自身中心旋转），
  -- 所以 `SetAnchoredPosition(x, y)` 设的是**中心点**，而不是左下角。
  -- 而 `LAYOUT.square_pos` 返回的是棋格**左下角**（文本框控件的 pivot 是 0，正好对上）。
  -- 旧代码把左下角坐标直接喂给图片控件，于是：
  --   · 空格圆点（直径 0.30 格）偏左下 0.35 格 —— 实测截图里绿点明显跑到格子左下方，
  --     还压到相邻格上；
  --   · 可吃子整格薄罩（边长 1 格）偏左下 0.5 格 —— 红圈正好盖住左下相邻格的四分之一，
  --     看起来完全对不上（issue 截图 1 里那个红圆就是它）。
  -- 正确做法：中心 = 左下角 + 边长/2。
  ANIM.hlBase = ANIM.hlBase or {}
  local idx = 0
  local board = GAME.st.board
  for to, _ in pairs(targets) do
    idx = idx + 1
    if idx > 28 then break end
    local tx, ty = LAYOUT.square_pos(L, to)
    -- 棋格中心（图片控件按中心定位，见上方说明）
    local cx, cy = tx + L.cell * 0.5, ty + L.cell * 0.5
    local c = UI.legalHL[idx]
    local isCap = (board[to] ~= 0)
    if isCap then
      -- 可吃子：整格薄罩（尺寸 = 一格，中心 = 格中心）
      c:SetSizeDelta(L.cell, L.cell)
      c:SetAnchoredPosition(cx, cy)
      c.imageColor = color_of(CONFIG.COLOR.LEGAL_CAP)
      ANIM.hlBase[idx] = { x = cx, y = cy, size = L.cell }
    else
      -- 空格：居中的圆点（尺寸 = 0.30 格，中心同样取格中心）
      local d = L.cell * 0.30
      c:SetSizeDelta(d, d)
      c:SetAnchoredPosition(cx, cy)
      c.imageColor = color_of(CONFIG.COLOR.LEGAL_HL)
      ANIM.hlBase[idx] = { x = cx, y = cy, size = d }
    end
    ui_set_active(c, true)
  end
  UI.legalHLUsed = idx
  if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.HINT_SELECTED end
  -- 音效：选中一枚自己的棋子（对应 Demo 第 1935 行 SFX.play("select")）
  sfx_play("select")
  return true
end

-- 尝试走子
local function try_move(toSq)
  if GAME.selected == nil then return false end
  if not GAME.legalTargets[toSq] then return false end

  -- 找出所有落到该格的走法（升变会有 4 条）
  local candidates = {}
  for _, mv in ipairs(GAME.legalMoves) do
    if mv.to == toSq then candidates[#candidates + 1] = mv end
  end
  if #candidates == 0 then return false end

  if #candidates > 1 and candidates[1].promo ~= nil then
    -- 需要玩家选升变
    GAME.pendingPromo = candidates
    show_promo()
    for sq = 0, 63 do
      if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], false) end
    end
    return true
  end

  apply_move(candidates[1])
  net_send_move(candidates[1])
  return true
end

-- 处理棋盘点击
local function on_square_clicked(sq)
  -- 复盘中棋盘只看不点（命中区本身也已 SetActive(false)，这里是第二道保险）
  if GAME.review ~= nil then return end
  if GAME.state ~= "RUNNING" or GAME.over or GAME.pendingPromo then return end

  -- 已选中且点的是合法落点 → 走子
  if GAME.selected ~= nil and GAME.legalTargets[sq] then
    try_move(sq)
    return
  end

  -- 点同一枚已选中的子 → 取消
  if GAME.selected == sq then
    clear_highlights()
    if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.HINT_OPENING end
    return
  end

  -- 尝试选中
  local ok = select_square(sq)
  if not ok then
    clear_highlights()
    if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.HINT_OPENING end
  end
end

-- =============================================================================
-- 第 8 区：INPUT（输入）
--   原生命中方案：每格一个光标检测区，回调闭包捕获格号，不读坐标。
-- =============================================================================
local INPUT = { registered = {} }

-- 点击事件枚举：沙箱叫 Click，真机文档叫 CursorClick。两边兼容。
local function resolve_click_event()
  local ok, ev = pcall(function() return Enum.CursorEventType.CursorClick end)
  if ok and ev ~= nil then return ev end
  ok, ev = pcall(function() return Enum.CursorEventType.Click end)
  if ok and ev ~= nil then return ev end
  return nil
end

local CLICK_EVENT = nil

-- 【音效：面板按钮统一点击音】对应 Demo 的 `withClick` 包装（chess_demo.html 第 1416 行）：
--   `const withClick = (fn) => (e) => { e.stopPropagation(); SFX.play("click"); fn(); };`
-- 为什么做成包装而不是在 15 个回调里各写一行：漏一个就是「有一个按钮没声音」，
-- 而且以后加按钮还得记得加。包在 register_click 外面，新按钮自动带上。
-- 【棋盘格不放点击音】走子/选中各有专用音效（MOVE/CAPTURE/CHECK/SELECT），
-- 再叠一个 click 会变成「两声」，Demo 也是棋盘格不播 click。
local function with_click(fn)
  return function()
    sfx_play("click")
    return fn()
  end
end

local function register_click(ctrl, fn)
  if ctrl == nil or CLICK_EVENT == nil then return false end
  local ok = pcall(function()
    ctrl:AddCursorEventListener(CLICK_EVENT, function(data)
      local handled = fn()
      return handled ~= false
    end)
  end)
  if ok then
    INPUT.registered[#INPUT.registered + 1] = ctrl
    return true
  end
  return false
end

local function register_all_input()
  -- 64 个棋盘格
  for sq = 0, 63 do
    register_click(UI.hitAreas[sq], function() on_square_clicked(sq); return true end)
  end
  -- 侧面板按钮
  -- 新开一局：按 C-02 先确认「重开会清空这一局」
  register_click(UI.panel.hitNew, with_click(function()
    if GAME.over then new_game(); return true end
    show_confirm("newgame")
    return true
  end))
  -- 认输：按 C-01 先确认「认输就直接判负，确定吗」
  register_click(UI.panel.hitResign, with_click(function()
    if GAME.over then return true end
    show_confirm("resign")
    return true
  end))
  -- 求和：本地同屏直接按 C-04 询问对方；联机发 EV_DRAW_REQ
  register_click(UI.panel.hitDraw, with_click(function()
    if GAME.over then return true end
    local sideIdx = (GAME.st.turn == WHITE) and 1 or 2
    if GAME.drawCooldown[sideIdx] > 0 then
      if UI.panel.hint then UI.panel.hint.text = CONFIG.TEXT.BTN_DRAW_USED end
      return true
    end
    GAME.drawCooldown[sideIdx] = CONFIG.DRAW_COOLDOWN_SEC
    if GAME.localMode then
      show_confirm("draw")
    else
      -- 发之前先置标记：服务端会把我这条请求广播回我自己，
      -- 收到回声时靠这个标记识别并丢弃（见第 9 区 EV_DRAW_REQ 的回声过滤）。
      GAME.drawReqSent = true
      if not net_send_event(CONFIG.EV_DRAW_REQ, sideIdx - 1, 0, 0, "") then
        GAME.drawReqSent = false      -- 发送失败就别留标记，否则会误吞下一条真实请求
      end
    end
    return true
  end))
  -- 切换同屏/联机：按 C-03 先确认「切换会断开这一局，确定吗」
  register_click(UI.panel.hitLocal, with_click(function()
    show_confirm("switch")
    return true
  end))
  -- 结算面板「再来一局」
  register_click(UI.result.hitAgain, with_click(function() new_game(); return true end))
  -- 结算面板「复盘」（v1.6）：进入复盘，默认停在最后一步
  register_click(UI.result.hitReview, with_click(function()
    enter_review()
    return true
  end))
  -- 面板第三行常驻键：对局中「看历史」/ 复盘中「退出复盘」（v1.6）
  register_click(UI.review.hitToggle, with_click(function()
    if GAME.review ~= nil then
      exit_review()
    else
      if GAME.pendingPromo then return true end
      enter_review()
    end
    return true
  end))
  -- 复盘四个翻页键（v1.6）
  register_click(UI.review.hitStart, with_click(function() review_goto(0, nil); return true end))
  register_click(UI.review.hitPrev,  function() review_goto(nil, -1); return true end)
  register_click(UI.review.hitNext,  function() review_goto(nil, 1); return true end)
  register_click(UI.review.hitEnd,   function() review_goto(#GAME.history - 1, nil); return true end)
  -- 升变四选一
  for i = 1, 4 do
    register_click(UI.promo.hits[i], with_click(function()
      if not GAME.pendingPromo then return true end
      local promoPieces = { QUEEN, ROOK, BISHOP, KNIGHT }
      local want = promoPieces[i]
      local chosen = nil
      for _, mv in ipairs(GAME.pendingPromo) do
        if mv.promo == want then chosen = mv; break end
      end
      GAME.pendingPromo = nil
      hide_promo()
      if chosen then
        for sq = 0, 63 do
          if UI.hitAreas[sq] then ui_set_active(UI.hitAreas[sq], true) end
        end
        -- 音效：升变确认的琶音（对应 Demo 第 2041 行 SFX.play("promote")，
        -- 时机是「选完棋子、真正 applyMove 之前」，与这里一致）
        sfx_play("promote")
        apply_move(chosen)
        net_send_move(chosen)
      end
      return true
    end))
  end
  -- 音效开关（v1.10）
  -- 【不带 with_click】这个按钮自己就是「音效总开关」：
  --   关的时候播 click 会让人以为没关掉；开的时候 sfx_toggle 内部已经播了一声确认音。
  register_click(UI.panel.hitSfx, function()
    sfx_toggle()
    sync_sfx_button()
    return true
  end)
  -- 确认弹窗：确定
  register_click(UI.confirm.hitYes, with_click(function()
    local kind = GAME.confirmKind
    hide_confirm()
    if kind == "resign" then
      if GAME.over then return true end
      GAME.over = true
      -- 【认输方判定必须看「谁点的按钮」，不能看「轮到谁」】
      -- 同屏模式下点按钮的人与当前轮次一致，两者等价；
      -- 联机模式下我可以在对方回合点认输（例如思考时直接投降），
      -- 此时 st.turn 是对方，用它会把自己认输写成对方认输（模拟器实测踩到：
      -- 黑方回合白方点认输，结算显示「黑方点了认输」）。
      -- 因此：联机模式用 GAME.mySide，同屏模式用当前轮次。
      local resignSide
      if GAME.localMode then
        resignSide = (GAME.st.turn == WHITE) and 1 or 2
      else
        resignSide = GAME.mySide
      end
      if resignSide == 1 then
        GAME.resultText = CONFIG.TEXT.RESULT_RESIGN_WHITE
        GAME.resultSub = CONFIG.TEXT.SUB_RESIGN_WHITE
        net_send_event(CONFIG.EV_RESIGN, 0, 0, 0, "")
      else
        GAME.resultText = CONFIG.TEXT.RESULT_RESIGN_BLACK
        GAME.resultSub = CONFIG.TEXT.SUB_RESIGN_BLACK
        net_send_event(CONFIG.EV_RESIGN, 1, 0, 0, "")
      end
      -- 音效：认输按下瞬间的「错误/否定」提示（对应 Demo 的 doResign 语义）。
      -- 先播 RESIGN 再 show_result（后者会播 GAME_END），两声叠起来是「确认+收尾」。
      sfx_play("resign")
      show_result()
    elseif kind == "newgame" then
      new_game()
    elseif kind == "switch" then
      GAME.localMode = not GAME.localMode
      if UI.panel.hint then
        UI.panel.hint.text = GAME.localMode and "已切换到同屏轮流" or CONFIG.TEXT.TURN_WHITE
      end
    elseif kind == "draw" then
      GAME.over = true
      GAME.resultText = CONFIG.TEXT.RESULT_DRAW_AGREED
      GAME.resultSub = CONFIG.TEXT.SUB_DRAW_AGREED
      show_result()
      net_send_event(CONFIG.EV_DRAW_ACC, 0, 0, 0, "")
    end
    return true
  end))
  -- 确认弹窗：取消
  register_click(UI.confirm.hitNo, with_click(function()
    local kind = GAME.confirmKind
    hide_confirm()
    if kind == "draw" then
      if UI.panel.hint then UI.panel.hint.text = "对方拒绝和棋，继续对局" end
      net_send_event(CONFIG.EV_DRAW_NO, 0, 0, 0, "")
    end
    return true
  end))
end

-- =============================================================================
-- 第 9 区：NET（联机，能力探测 + 降级）
--   客户端发出 ChessSync；服务端节点图「收到即广播」由用户在编辑器里搭。
--   沙箱里 ServerSignal 没有 AddInt 方法，所以这里必须能力探测，不能直接调用。
-- =============================================================================
local NET = { canSend = false, canReceive = false, probed = false, lastSeq = -1 }

local function net_probe()
  NET.probed = true
  -- 探测发送能力
  local ok = pcall(function()
    local sig = game.ServerSignal(CONFIG.SIGNAL_NAME)
    if sig ~= nil and sig.AddInt ~= nil and sig.AddString ~= nil and sig.SendSignal ~= nil then
      NET.canSend = true
    end
  end)
  -- 探测接收能力
  pcall(function()
    if script ~= nil and script.RegisterServerSignalHandler ~= nil then
      NET.canReceive = true
    end
  end)
  log_info("联机能力探测：发送=%s 接收=%s", tostring(NET.canSend), tostring(NET.canReceive))
end

function net_send_event(eventType, a, b, c, fen)
  if not NET.canSend then return false end
  local ok = pcall(function()
    local sig = game.ServerSignal(CONFIG.SIGNAL_NAME)
    sig:AddInt(eventType)
    sig:AddInt(a or 0)
    sig:AddInt(b or 0)
    sig:AddInt(c or 0)
    sig:AddString(fen or "")
    sig:SendSignal()
  end)
  if not ok then
    NET.canSend = false
    log_err("信号发送失败，联机降级为同屏")
  end
  return ok
end

function net_send_move(mv)
  if not NET.canSend then return end
  local promoCode = 0
  if mv.promo == QUEEN then promoCode = 1
  elseif mv.promo == ROOK then promoCode = 2
  elseif mv.promo == BISHOP then promoCode = 3
  elseif mv.promo == KNIGHT then promoCode = 4 end
  -- 记下这一手，用于丢弃服务端广播回来的自己这条（见 net_on_signal 的 EV_MOVE 分支）。
  GAME.lastSentMove = { from = mv.from, to = mv.to, promo = promoCode }
  net_send_event(CONFIG.EV_MOVE, mv.from, mv.to, promoCode, "")
end

-- 收到信号：处理走子/新局/认输/求和/身份
local function net_on_signal(signalName, params)
  if GAME.state ~= "RUNNING" then return end
  if type(params) ~= "table" then return end
  local eventType = params[1]
  local a = params[2] or 0
  local b = params[3] or 0
  local c = params[4] or 0
  if type(eventType) ~= "number" then return end

  if eventType == CONFIG.EV_MOVE then
    -- 【回声过滤，必须先做】服务端节点图把我自己的走子也广播回给我。
    -- 我本地已经 apply_move 过了，再按「对方走子」重新验证必然失败
    -- （该起点格已空 → 找不到合法走法 → 误报 log_err「收到无法验证的走子信号」）。
    -- 用 lastSentMove 精确匹配（起点+终点+升变三项），匹配上就只清标记、不处理。
    local last = GAME.lastSentMove
    if last ~= nil and last.from == a and last.to == b and last.promo == c then
      GAME.lastSentMove = nil           -- 自己的回声，丢弃
    else
      -- 对方走了一步：本地重算并校验
      local promoPieces = { [0] = nil, [1] = QUEEN, [2] = ROOK, [3] = BISHOP, [4] = KNIGHT }
      local wantPromo = promoPieces[c]
      local candidates = {}
      for _, mv in ipairs(RULES.legal_moves(GAME.st)) do
        if mv.from == a and mv.to == b then
          if (wantPromo == nil and mv.promo == nil) or (wantPromo ~= nil and mv.promo == wantPromo) then
            candidates[#candidates + 1] = mv
          end
        end
      end
      if #candidates > 0 then
        apply_move(candidates[1])
      else
        log_err("收到无法验证的走子信号：%d→%d", a, b)
      end
    end

  elseif eventType == CONFIG.EV_NEWGAME then
    new_game()

  elseif eventType == CONFIG.EV_RESIGN then
    -- 【标题要用认输专名，不能用将死文案】
    -- 原先写 RESULT_BLACK_WIN（「黑方将死白方，黑方胜」），对方认输却显示将死，文案错位。
    -- 认输场景正确标题是 RESULT_RESIGN_WHITE / RESULT_RESIGN_BLACK。
    GAME.over = true
    if a == 0 then
      GAME.resultText = CONFIG.TEXT.RESULT_RESIGN_WHITE
      GAME.resultSub = CONFIG.TEXT.SUB_RESIGN_WHITE
    else
      GAME.resultText = CONFIG.TEXT.RESULT_RESIGN_BLACK
      GAME.resultSub = CONFIG.TEXT.SUB_RESIGN_BLACK
    end
    show_result()

  elseif eventType == CONFIG.EV_DRAW_REQ then
    -- 【必须传 kind】原先这里是不带参数的 show_confirm()，kind=nil 会走
    -- CONFIRM_SPEC.newgame 兜底 → 对方收到求和时弹出的是「重开会清空这一局」，
    -- 按钮文案也是「确定/取消」，不是「同意和棋/拒绝求和」（模拟器实测踩到）。
    --
    -- 【回声过滤】服务端节点图是「收到即广播给房间内所有人」，**包括发送者自己**。
    -- 不加过滤的话，发起求和的人会收到自己的请求并弹出「对方想和棋，同意吗」，
    -- 结果是发起者自己问自己（模拟器实测：Player1 点求和后自己弹出了同意框）。
    -- 用「我是否刚发出求和」这个标记吃掉回声：是回声就只清标记，不弹框。
    if GAME.drawReqSent then
      GAME.drawReqSent = false          -- 自己的回声，丢弃
    else
      show_confirm("draw")
    end

  elseif eventType == CONFIG.EV_DRAW_ACC then
    -- 同样有回声：同意方自己也会收到这条广播，而它已经本地结算过了。
    -- 用 GAME.over 挡住重复结算，避免结算面板被重入。
    if not GAME.over then
      GAME.over = true
      GAME.resultText = CONFIG.TEXT.RESULT_DRAW_AGREED
      GAME.resultSub = CONFIG.TEXT.SUB_DRAW_AGREED
      show_result()
    end

  elseif eventType == CONFIG.EV_DRAW_NO then
    if UI.panel.hint then UI.panel.hint.text = "对方拒绝和棋，继续对局" end

  elseif eventType == CONFIG.EV_ROLE then
    GAME.mySide = (a == 0) and 1 or 2
    if UI.panel.hint then
      UI.panel.hint.text = (GAME.mySide == 1) and "你是白方" or "你是黑方"
    end
  end
end

local function net_register_receive()
  if not NET.canReceive then return false end
  local ok = pcall(function()
    script:RegisterServerSignalHandler(CONFIG.SIGNAL_NAME, function(signalName, params)
      net_on_signal(signalName, params)
    end)
  end)
  if ok then
    log_info("已注册联机信号接收：%s", CONFIG.SIGNAL_NAME)
    return true
  end
  return false
end

