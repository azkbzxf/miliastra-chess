    bg = CONFIG.COLOR.BOARD_FRAME, text = "",
  })
  -- ③ 外框内圈高光（比本体再内收一点，形成 2px 亮边）
  local innerPad = framePad * 0.55
  UI.frameInner = create_text({
    name = "boardframeinner", parent = UI.host,
    x = bx - innerPad, y = by - innerPad,
    w = bs + innerPad * 2, h = bs + innerPad * 2,
    bg = CONFIG.COLOR.BOARD_FRAME_IN, text = "",
  })

  -- ===== 棋盘格底 64 =====
  for sq = 0, 63 do
    local x, y = LAYOUT.square_pos(L, sq)
    local isDark = ((sq // 8) + (sq % 8)) % 2 == 0
    UI.squares[sq] = create_text({
      name = "sq_" .. tostring(sq),
      parent = UI.host, x = x, y = y, w = L.cell, h = L.cell,
      bg = isDark and CONFIG.COLOR.SQ_DARK or CONFIG.COLOR.SQ_LIGHT,
      text = "",
      raycast = false,
    })
  end

  -- 坐标标注：列 a-h（棋盘下方）、行 1-8（棋盘左侧）
  -- 【浅色主题连带项：必须让开暖木外框】v1.7 起棋盘外面多了一圈 framePad = cell*0.16 的外框。
